import React, { useState } from "react";
import { Form, ActionPanel, Action, showToast, Toast, Clipboard } from "@raycast/api";

export default function Command() {
  const [client, setClient] = useState("Acme Corp");
  const [project, setProject] = useState("Mobile App MVP");
  const [features, setFeatures] = useState("Custom OAuth Integration, Export to Excel, Multi-tenant Webhooks");
  const [hours, setHours] = useState("14");
  const [rate, setRate] = useState("125");

  const parsedHours = parseFloat(hours) || 0;
  const parsedRate = parseFloat(rate) || 0;
  const totalBleed = parsedHours * parsedRate;

  async function handleSubmit() {
    const report = `========================================================
⚡ SCOPELOCK AI : SCOPE EXPOSURE & REVENUE BLEED AUDIT
========================================================
Client: ${client}
Project: ${project}
Uncontracted Scope Additions:
${features}

• Unbilled Engineering Hours: ${parsedHours} hrs
• Billing Rate: $${parsedRate}/hr
• UNRECOVERED REVENUE EXPOSURE: $${totalBleed.toLocaleString()} USD
• Statutory Legal Protection: UCC § 2-209 Enforceable Written Modification

Generated by ScopeLock AI (https://ahirwardhanmanti83-bit.github.io/scopelock-ai/)
========================================================`;

    await Clipboard.copy(report);
    await showToast({
      style: Toast.Style.Success,
      title: "Audit Report Copied!",
      message: `$${totalBleed.toLocaleString()} unrecovered revenue audit copied to clipboard`,
    });
  }

  return (
    <Form
      actions={
        <ActionPanel>
          <Action.SubmitForm title="Copy Audit Report" onSubmit={handleSubmit} />
          <Action.OpenInBrowser
            title="Open ScopeLock Web Dashboard"
            url={`https://ahirwardhanmanti83-bit.github.io/scopelock-ai/?client=${encodeURIComponent(client)}&hours=${parsedHours}&bleed=${totalBleed}`}
          />
        </ActionPanel>
      }
    >
      <Form.Description
        title="Scope Creep Auditor"
        text={`Current Unrecovered Bleed: $${totalBleed.toLocaleString()} USD (${parsedHours} unbilled hours)`}
      />
      <Form.TextField id="client" title="Client Name" value={client} onChange={setClient} placeholder="e.g. Acme Corp" />
      <Form.TextField id="project" title="Project Name" value={project} onChange={setProject} placeholder="e.g. SaaS MVP Redesign" />
      <Form.TextArea id="features" title="Out-of-Scope Requests" value={features} onChange={setFeatures} placeholder="Describe extra features requested by client..." />
      <Form.TextField id="hours" title="Estimated Extra Hours" value={hours} onChange={setHours} placeholder="e.g. 14" />
      <Form.TextField id="rate" title="Hourly Rate ($/hr)" value={rate} onChange={setRate} placeholder="e.g. 125" />
    </Form>
  );
}
